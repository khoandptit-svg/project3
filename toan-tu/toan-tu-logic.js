/** Toán tử logic :
 * &&      --> Và (And)
 * ||      --> Hoặc (Or)
 * !       --> Phủ định (Not)
 */

// VD && và || :
var a = 1 ;
var b = 2 ;
var c = 3 ;
if (a > 0 && b > 0 && c > 0 ) {
    console.log("Điều kiện đúng");
}

// VD ! phủ định :
var a = 1 ;
var b = 2 ;
var c = 3 ;
if (!(a > 0 )) {
    console.log("Điều kiện đúng");
}