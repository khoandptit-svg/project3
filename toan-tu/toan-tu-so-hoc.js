/** Toán tử số học - Arithmetic :
+          --> Cộng
-          --> Trừ
*          --> Nhân
**         --> Lũy thừa
/          --> Chia
%          --> Chia lấy dư
++         --> Tăng 1 đơn vị
--         --> Giảm 1 đơn vị
*/

// Ví dụ :+ Cộng , - Trừ , * Nhân , / Chia :
var a = 8;
var b = 2;
var c = a % b;
console.log(c);

// ví dụ : ++ Tăng 1 đơn vị ; -- Giảm 1 đơn vị :
var d = 5;
d++;
console.log(d);

// Toán tư ++ , -- có thể đặt trước hoặc sau biến:
// Prefix and postfix :
var a = 6 ;
var output = a++ ;
console.log(output); // 6
console.log(a);     // 7   

 

